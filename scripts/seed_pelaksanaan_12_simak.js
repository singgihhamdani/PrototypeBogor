async function seed12Simak() {
  console.log('Seeding 12 SIMAK records into public.pengawasan_sesi on Supabase...');
  for (const row of records12) {
    const { error } = await supabase
      .from('pengawasan_sesi')
      .upsert([row], { onConflict: 'id' });
    if (error) {
      console.error(`Error upserting ${row.id} (${row.simak_code}):`, error.message);
    } else {
      console.log(`✅ Sukses seed ${row.id} untuk SIMAK ${row.simak_code}`);
    }
  }
  console.log('🎉 Seeding 12 SIMAK selesai!');
}

seed12Simak();
